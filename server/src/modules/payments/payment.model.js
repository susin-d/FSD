const mongoose = require("mongoose");

const paymentSchema = new mongoose.Schema(
  {
    booking: { type: mongoose.Schema.Types.ObjectId, ref: "Booking", required: true, unique: true, index: true },
    customer: { type: mongoose.Schema.Types.ObjectId, ref: "User", required: true, index: true },
    provider: { type: mongoose.Schema.Types.ObjectId, ref: "ProviderProfile", required: true },
    providerAccountId: { type: String, required: true },
    amountPaise: { type: Number, required: true, min: 1 },
    commissionPaise: { type: Number, required: true, min: 0 },
    commissionBps: { type: Number, required: true, min: 0, max: 10000 },
    providerAmountPaise: { type: Number, required: true, min: 1 },
    currency: { type: String, default: "INR", enum: ["INR"] },
    status: { type: String, enum: ["creating", "created", "paid", "failed", "expired", "refunded", "partially_refunded"], default: "creating", index: true },
    razorpayOrderId: { type: String, index: true, sparse: true },
    razorpayOrderIds: { type: [String], default: [] },
    razorpayPaymentId: { type: String, index: true, sparse: true },
    capturedPaymentIds: { type: [String], default: [] },
    duplicateCaptureRefunds: [{
      paymentId: { type: String, required: true },
      orderId: { type: String, required: true },
      amountPaise: { type: Number, required: true },
      status: { type: String, enum: ["pending", "refunded", "reconciliation_required"], default: "pending" },
      refundId: { type: String, default: null },
      requestStarted: { type: Boolean, default: false },
    }],
    attemptHistory: [{
      orderId: { type: String, default: null },
      paymentId: { type: String, default: null },
      status: { type: String, default: "" },
      refundedAmountPaise: { type: Number, default: 0 },
      providerRefundedAmountPaise: { type: Number, default: 0 },
      refundIds: { type: [String], default: [] },
      transferId: { type: String, default: null },
      transferStatus: { type: String, default: "not_created" },
      recordedAt: { type: Date, default: Date.now },
    }],
    captureProcessingLeaseUntil: { type: Date, default: null },
    razorpayTransferId: { type: String, default: null },
    transferStatus: { type: String, enum: ["not_created", "held", "released", "reversed", "failed"], default: "not_created" },
    transferCreationLeaseUntil: { type: Date, default: null },
    transferCreateStartedAt: { type: Date, default: null },
    routeReversalOperation: {
      key: { type: String, default: null },
      amountPaise: { type: Number, default: null },
      status: { type: String, enum: ["pending", "completed", "reconciliation_required"], default: null },
      refundId: { type: String, default: null },
      transferId: { type: String, default: null },
      reversalId: { type: String, default: null },
    },
    checkoutExpiresAt: { type: Date, required: true, index: true },
    refundedAmountPaise: { type: Number, default: 0, min: 0 },
    providerRefundedAmountPaise: { type: Number, default: 0, min: 0 },
    refundIds: { type: [String], default: [] },
    refundInProgress: { type: Boolean, default: false },
    refundProcessingLeaseUntil: { type: Date, default: null },
    refundOperation: {
      key: { type: String, default: null },
      amountPaise: { type: Number, default: null },
      previousRefundedPaise: { type: Number, default: null },
      status: { type: String, enum: ["pending", "completed", "failed", "reconciliation_required"], default: null },
      requestStarted: { type: Boolean, default: false },
      reason: { type: String, default: "" },
      refundId: { type: String, default: null },
    },
    refundReconciliationRequired: { type: Boolean, default: false },
    orderCreationReconciliationRequired: { type: Boolean, default: false },
    transferReconciliationRequired: { type: Boolean, default: false },
    checkoutSignatureVerifiedAt: { type: Date, default: null },
    lastError: { type: String, maxlength: 1000, default: "" },
  },
  { timestamps: true }
);

module.exports = mongoose.models.Payment || mongoose.model("Payment", paymentSchema);
